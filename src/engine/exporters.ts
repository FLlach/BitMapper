import { DataType, HeaderOptions, SequenceFrame, ESP32Sketches } from '../types';

/**
 * Format a number to 0xXXXX (16-bit) or 0xXX (8-bit)
 */
export function toHex(val: number, dataType: DataType = 'uint16_t'): string {
  if (dataType === 'uint16_t') {
    return '0x' + (val & 0xffff).toString(16).toUpperCase().padStart(4, '0');
  }
  return '0x' + (val & 0xff).toString(16).toUpperCase().padStart(2, '0');
}

/**
 * Generate a C/C++ Header (.h) for a single bitmap
 */
export function generateCHeaderSingle(
  name: string,
  width: number,
  height: number,
  values: number[],
  dataType: DataType,
  options: HeaderOptions = {}
): string {
  const {
    colorFormat = 'rgb565',
    endian = 'big',
    swapBytes = false,
    useProgmem = true,
    itemsPerLine = dataType === 'uint16_t' ? 12 : 16
  } = options;

  const safeName = name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  const upperName = safeName.toUpperCase();
  const progmemStr = useProgmem ? 'PROGMEM ' : '';

  const chunks: string[] = [];
  chunks.push(`// =============================================================================\n`);
  chunks.push(`// Generated by BitMapper Studio for Microcontrollers\n`);
  chunks.push(`// Dimensions: ${width} x ${height} px\n`);
  chunks.push(`// Color Format: ${colorFormat.toUpperCase()} (${dataType})\n`);
  chunks.push(`// Endianness: ${endian.toUpperCase()} | Byte Swap: ${swapBytes}\n`);
  chunks.push(`// Data Length: ${values.length} elements (${values.length * (dataType === 'uint16_t' ? 2 : 1)} bytes)\n`);
  chunks.push(`// Date: ${new Date().toISOString()}\n`);
  chunks.push(`// =============================================================================\n\n`);
  chunks.push(`#pragma once\n`);
  chunks.push(`#include <Arduino.h>\n\n`);
  chunks.push(`#define ${upperName}_WIDTH ${width}\n`);
  chunks.push(`#define ${upperName}_HEIGHT ${height}\n`);
  chunks.push(`#define ${upperName}_SIZE ${values.length}\n\n`);
  chunks.push(`const ${dataType} ${safeName}_data[${values.length}] ${progmemStr}= {\n`);

  let currentLine = '  ';
  const total = values.length;
  for (let i = 0; i < total; i++) {
    currentLine += toHex(values[i], dataType);
    if (i < total - 1) {
      currentLine += ', ';
    }
    if ((i + 1) % itemsPerLine === 0 || i === total - 1) {
      chunks.push(currentLine + '\n');
      currentLine = '  ';
    }
  }

  chunks.push(`};\n`);
  return chunks.join('');
}

/**
 * Generate a C/C++ Header (.h) for an animated video sequence of frames
 */
export function generateCHeaderSequence(
  name: string,
  width: number,
  height: number,
  frames: SequenceFrame[],
  dataType: DataType,
  fps = 15,
  options: HeaderOptions = {}
): string {
  if (frames.length === 0) return '// Error: Secuencia de fotogramas vacía\n';

  const {
    colorFormat = 'rgb565',
    endian = 'big',
    swapBytes = false,
    useProgmem = true,
    itemsPerLine = dataType === 'uint16_t' ? 12 : 16
  } = options;

  const safeName = name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  const upperName = safeName.toUpperCase();
  const progmemStr = useProgmem ? 'PROGMEM ' : '';
  const frameDelay = Math.round(1000 / Math.max(1, fps));
  const bytesPerFrame = frames[0].values.length * (dataType === 'uint16_t' ? 2 : 1);
  const totalBytes = bytesPerFrame * frames.length;

  const chunks: string[] = [];
  chunks.push(`// =============================================================================\n`);
  chunks.push(`// Generated by BitMapper Studio - Animated Video Sequence\n`);
  chunks.push(`// Dimensions: ${width} x ${height} px\n`);
  chunks.push(`// Frame Count: ${frames.length} frames @ ${fps} FPS (Delay: ${frameDelay} ms)\n`);
  chunks.push(`// Color Format: ${colorFormat.toUpperCase()} (${dataType})\n`);
  chunks.push(`// Endianness: ${endian.toUpperCase()} | Byte Swap: ${swapBytes}\n`);
  chunks.push(`// Total Size: ${(totalBytes / 1024).toFixed(1)} KB in Flash Memory\n`);
  chunks.push(`// =============================================================================\n\n`);
  chunks.push(`#pragma once\n`);
  chunks.push(`#include <Arduino.h>\n\n`);
  chunks.push(`#define ${upperName}_WIDTH ${width}\n`);
  chunks.push(`#define ${upperName}_HEIGHT ${height}\n`);
  chunks.push(`#define ${upperName}_FRAME_COUNT ${frames.length}\n`);
  chunks.push(`#define ${upperName}_FRAME_RATE ${fps}\n`);
  chunks.push(`#define ${upperName}_FRAME_DELAY_MS ${frameDelay}\n\n`);

  for (let idx = 0; idx < frames.length; idx++) {
    const frame = frames[idx];
    const vals = frame.values;
    const len = vals.length;
    chunks.push(`const ${dataType} ${safeName}_frame_${idx}[${len}] ${progmemStr}= {\n`);

    let line = '  ';
    for (let i = 0; i < len; i++) {
      line += toHex(vals[i], dataType);
      if (i < len - 1) {
        line += ', ';
      }
      if ((i + 1) % itemsPerLine === 0 || i === len - 1) {
        chunks.push(line + '\n');
        line = '  ';
      }
    }
    chunks.push(`};\n\n`);
  }

  chunks.push(`// Array de punteros a todos los fotogramas\n`);
  chunks.push(`const ${dataType}* const ${safeName}_frames[${frames.length}] ${progmemStr}= {\n`);
  for (let idx = 0; idx < frames.length; idx++) {
    const isLast = idx === frames.length - 1;
    chunks.push(`  ${safeName}_frame_${idx}${isLast ? '' : ','}\n`);
  }
  chunks.push(`};\n`);

  return chunks.join('');
}

/**
 * Generate a MicroPython script (.py)
 */
export function generateMicroPython(
  name: string,
  width: number,
  height: number,
  bytes: Uint8Array
): string {
  const safeName = name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  let hexBytes = '';
  for (let i = 0; i < bytes.length; i++) {
    hexBytes += '\\x' + bytes[i].toString(16).padStart(2, '0');
  }

  return `# MicroPython bitmap data generated by BitMapper Studio
WIDTH = ${width}
HEIGHT = ${height}
${safeName.toUpperCase()}_DATA = bytearray(b"${hexBytes}")
`;
}

/**
 * Generate a clean Hex dump
 */
export function generateHexDump(bytes: Uint8Array, itemsPerLine = 16): string {
  const lines: string[] = [];
  for (let i = 0; i < bytes.length; i += itemsPerLine) {
    const slice = bytes.slice(i, i + itemsPerLine);
    const hex = Array.from(slice).map(b => b.toString(16).toUpperCase().padStart(2, '0')).join(' ');
    lines.push(hex);
  }
  return lines.join('\n');
}

/**
 * Generate ready-to-run ESP32 C++ sketches for popular display libraries
 */
export function generateESP32Sketches(
  name: string,
  width: number,
  height: number,
  isVideo = false,
  fps = 15
): ESP32Sketches {
  const safeName = name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  const upper = safeName.toUpperCase();

  const tftEspiSketch = `/*
 * ESP32 + TFT_eSPI (ST7789 / ILI9341) Bitmap Demo
 * Generated by BitMapper Studio
 */
#include <TFT_eSPI.h>
#include "${safeName}.h"

TFT_eSPI tft = TFT_eSPI();

void setup() {
  Serial.begin(115200);
  tft.init();
  tft.setRotation(0);
  tft.fillScreen(TFT_BLACK);

  // If colors appear byte-swapped, toggle this between true and false:
  tft.setSwapBytes(true);

  ${isVideo ? `
  // Display the first frame
  tft.pushImage(0, 0, ${upper}_WIDTH, ${upper}_HEIGHT, ${safeName}_frames[0]);
  ` : `
  // Draw bitmap at (x=0, y=0)
  tft.pushImage(0, 0, ${upper}_WIDTH, ${upper}_HEIGHT, ${safeName}_data);
  `}
}

void loop() {
  ${isVideo ? `
  // Play video animation in an endless loop
  for (int i = 0; i < ${upper}_FRAME_COUNT; i++) {
    tft.pushImage(0, 0, ${upper}_WIDTH, ${upper}_HEIGHT, ${safeName}_frames[i]);
    delay(${upper}_FRAME_DELAY_MS);
  }
  ` : `
  delay(1000);
  `}
}
`;

  const adafruitSketch = `/*
 * ESP32 + Adafruit_ST7789 Bitmap Demo
 * Generated by BitMapper Studio
 */
#include <Adafruit_GFX.h>
#include <Adafruit_ST7789.h>
#include <SPI.h>
#include "${safeName}.h"

#define TFT_CS    5
#define TFT_DC    2
#define TFT_RST   4
#define TFT_MOSI  23
#define TFT_SCLK  18

Adafruit_ST7789 tft = Adafruit_ST7789(TFT_CS, TFT_DC, TFT_RST);

void setup() {
  Serial.begin(115200);
  tft.init(${width}, ${height});
  tft.setRotation(0);
  tft.fillScreen(ST77XX_BLACK);

  ${isVideo ? `
  tft.drawRGBBitmap(0, 0, ${safeName}_frames[0], ${upper}_WIDTH, ${upper}_HEIGHT);
  ` : `
  tft.drawRGBBitmap(0, 0, ${safeName}_data, ${upper}_WIDTH, ${upper}_HEIGHT);
  `}
}

void loop() {
  ${isVideo ? `
  for (int i = 0; i < ${upper}_FRAME_COUNT; i++) {
    tft.drawRGBBitmap(0, 0, ${safeName}_frames[i], ${upper}_WIDTH, ${upper}_HEIGHT);
    delay(${upper}_FRAME_DELAY_MS);
  }
  ` : `
  delay(1000);
  `}
}
`;

  const lovyanSketch = `/*
 * ESP32 + LovyanGFX (ST7789 / GC9A01) Ultra-Fast DMA Bitmap Demo
 * Generated by BitMapper Studio
 */
#define LGFX_USE_V1
#include <LovyanGFX.hpp>
#include "${safeName}.h"

LGFX lcd;

void setup() {
  Serial.begin(115200);
  lcd.init();
  lcd.fillScreen(TFT_BLACK);
  lcd.setSwapBytes(true);

  ${isVideo ? `
  lcd.pushImage(0, 0, ${upper}_WIDTH, ${upper}_HEIGHT, ${safeName}_frames[0]);
  ` : `
  lcd.pushImage(0, 0, ${upper}_WIDTH, ${upper}_HEIGHT, ${safeName}_data);
  `}
}

void loop() {
  ${isVideo ? `
  for (int i = 0; i < ${upper}_FRAME_COUNT; i++) {
    lcd.pushImage(0, 0, ${upper}_WIDTH, ${upper}_HEIGHT, ${safeName}_frames[i]);
    delay(${upper}_FRAME_DELAY_MS);
  }
  ` : `
  delay(1000);
  `}
}
`;

  const binaryFsSketch = `/*
 * ESP32 + LittleFS / SD Card Stream to ST7789
 * Reads .bin raw bitmaps directly from flash memory
 * Generated by BitMapper Studio
 */
#include <TFT_eSPI.h>
#include <LittleFS.h>

TFT_eSPI tft = TFT_eSPI();

void drawBinFromFS(const char *filename, int x, int y, int w, int h) {
  File file = LittleFS.open(filename, "r");
  if (!file) {
    Serial.println("Failed to open file");
    return;
  }

  uint16_t lineBuffer[w];
  tft.setSwapBytes(true);

  for (int row = 0; row < h; row++) {
    file.read((uint8_t*)lineBuffer, w * 2);
    tft.pushImage(x, y + row, w, 1, lineBuffer);
  }
  file.close();
}

void setup() {
  Serial.begin(115200);
  tft.init();
  LittleFS.begin();
  tft.fillScreen(TFT_BLACK);

  drawBinFromFS("/${safeName}.bin", 0, 0, ${width}, ${height});
}

void loop() {
  delay(1000);
}
`;

  return {
    tft_espi: tftEspiSketch,
    adafruit_gfx: adafruitSketch,
    lovyangfx: lovyanSketch,
    fs_binary: binaryFsSketch
  };
}

export const BMPR_MAGIC = 'BMPR';
export const BMPR_VERSION = 1;

/**
 * Genera una cabecera binaria de 16 bytes de metadatos BMPR
 */
export function createBmprHeader(
  width: number,
  height: number,
  totalFrames: number = 1,
  fps: number = 15,
  colorFormat: string = 'rgb565',
  swapBytes: boolean = true
): Uint8Array {
  const header = new Uint8Array(16);
  const view = new DataView(header.buffer);

  // magic: 'B', 'M', 'P', 'R'
  header[0] = 0x42; // 'B'
  header[1] = 0x4d; // 'M'
  header[2] = 0x50; // 'P'
  header[3] = 0x52; // 'R'

  view.setUint16(4, BMPR_VERSION, true);
  view.setUint16(6, width, true);
  view.setUint16(8, height, true);
  view.setUint16(10, totalFrames, true);
  view.setUint8(12, fps);

  let formatCode = 0;
  if (colorFormat === 'bgr565') formatCode = 1;
  else if (colorFormat === 'rgb888') formatCode = 2;
  else if (colorFormat === 'gray8') formatCode = 3;
  else if (colorFormat === 'mono1_horizontal') formatCode = 4;
  else if (colorFormat === 'mono1_vertical') formatCode = 5;

  view.setUint8(13, formatCode);

  let flags = 0;
  if (swapBytes) flags |= 0x01;
  view.setUint16(14, flags, true);

  return header;
}

/**
 * Combina la cabecera BMPR de 16 bytes con los datos binarios de píxeles
 */
export function generateBmprBinary(
  width: number,
  height: number,
  rawBytes: Uint8Array,
  totalFrames: number = 1,
  fps: number = 15,
  colorFormat: string = 'rgb565',
  swapBytes: boolean = true
): Uint8Array {
  const header = createBmprHeader(width, height, totalFrames, fps, colorFormat, swapBytes);
  const combined = new Uint8Array(header.length + rawBytes.length);
  combined.set(header, 0);
  combined.set(rawBytes, header.length);
  return combined;
}

